ALTER TABLE permisos_bano RENAME TO permisos_bano_antigua;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM permisos_bano_antigua permiso
        LEFT JOIN alumnos
            ON alumnos.nombre || ' ' || alumnos.apellidos = permiso.alumno
        LEFT JOIN profesores
            ON profesores.nombre || ' ' || profesores.apellidos = permiso.profesor
        LEFT JOIN grupos
            ON grupos.codigo = permiso.grupo
        WHERE alumnos.id IS NULL
           OR profesores.id IS NULL
           OR grupos.id IS NULL
           OR alumnos.grupo_id <> grupos.id
           OR substring(permiso.franja_horaria FROM '^[1-6]') IS NULL
    ) THEN
        RAISE EXCEPTION 'Hay permisos antiguos sin alumno, profesor, grupo o franja coincidente. No se modificaron los datos.';
    END IF;
END
$$;

CREATE TABLE permisos_bano (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_id BIGINT NOT NULL REFERENCES alumnos(id),
    profesor_id BIGINT NOT NULL REFERENCES profesores(id),
    franja_horaria_id BIGINT NOT NULL REFERENCES franjas_horarias(id),
    fecha DATE NOT NULL,
    hora TIME WITHOUT TIME ZONE NOT NULL,
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO permisos_bano (id, alumno_id, profesor_id, franja_horaria_id, fecha, hora, creado_en)
