       antiguo.creado_en
FROM permisos_bano_antigua antiguo
JOIN alumnos alumno
    ON alumno.nombre || ' ' || alumno.apellidos = antiguo.alumno
JOIN profesores profesor
    ON profesor.nombre || ' ' || profesor.apellidos = antiguo.profesor
JOIN grupos grupo
    ON grupo.codigo = antiguo.grupo
   AND alumno.grupo_id = grupo.id
JOIN franjas_horarias franja
    ON franja.numero = substring(antiguo.franja_horaria FROM '^[1-6]')::integer;

SELECT setval(
    pg_get_serial_sequence('permisos_bano', 'id'),
    COALESCE((SELECT MAX(id) FROM permisos_bano), 1),
    EXISTS (SELECT 1 FROM permisos_bano)
);

